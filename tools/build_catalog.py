#!/usr/bin/env python3
"""Build package/contents/code/catalog.js from d3-celestial's data files
(BSD-3-Clause, (c) Olaf Frohn; positions from Hipparcos).
Usage: build_catalog.py <d3-celestial data dir> <out.js>"""
import json, sys, os

src, out = sys.argv[1], sys.argv[2]
load = lambda f: json.load(open(os.path.join(src, f), encoding="utf-8"))
MAG = 5.5

stars = load("stars.6.json")["features"]
names = load("starnames.json")
flat, named = [], []
for f in stars:
    mag = f["properties"]["mag"]
    if mag is None or mag > MAG:
        continue
    ra, dec = f["geometry"]["coordinates"]
    try:
        bv = float(f["properties"]["bv"])
    except (TypeError, ValueError):
        bv = 0.6
    ra = ra % 360
    flat += [round(ra, 3), round(dec, 3), round(mag, 2), round(bv, 2)]
    n = names.get(str(f["id"]), {}).get("name", "")
    if n and mag <= 2.6:
        named.append([n, round(ra, 3), round(dec, 3), round(mag, 2)])

lines = []
for f in load("constellations.lines.json")["features"]:
    for seg in f["geometry"]["coordinates"]:
        pts = []
        for ra, dec in seg:
            pts += [round(ra % 360, 2), round(dec, 2)]
        lines.append(pts)

cons = []
for f in load("constellations.json")["features"]:
    ra, dec = f["geometry"]["coordinates"]
    cons.append([f["properties"]["name"], round(ra % 360, 2), round(dec, 2), int(f["properties"]["rank"])])

named.sort(key=lambda s: s[3])
with open(out, "w", encoding="utf-8") as o:
    o.write(".pragma library\n\n")
    o.write("// Generated by tools/build_catalog.py from d3-celestial v0.7.32 data\n")
    o.write("// (BSD-3-Clause, Copyright (c) 2015 Olaf Frohn; positions from Hipparcos).\n")
    o.write("// RA/Dec in degrees, J2000.\n\n")
    o.write("// [ra, dec, mag, B-V] x n, magnitude <= %.1f\n" % MAG)
    o.write("var STARS = " + json.dumps(flat, separators=(",", ":")) + "\n\n")
    o.write("// [name, ra, dec, mag] for the named stars brighter than 2.6\n")
    o.write("var NAMED = " + json.dumps(named, ensure_ascii=False, separators=(",", ":")) + "\n\n")
    o.write("// constellation stick figures: [ra, dec, ra, dec, ...] per polyline\n")
    o.write("var LINES = " + json.dumps(lines, separators=(",", ":")) + "\n\n")
    o.write("// [name, ra, dec, rank] label positions\n")
    o.write("var CONSTELLATIONS = " + json.dumps(cons, ensure_ascii=False, separators=(",", ":")) + "\n")
print(len(flat) // 4, "stars,", len(named), "named,", len(lines), "lines,", len(cons), "constellations")
