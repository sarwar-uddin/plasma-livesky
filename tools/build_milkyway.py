#!/usr/bin/env python3
"""Build package/contents/code/milkyway.js from d3-celestial's mw.json
(BSD-3-Clause, (c) Olaf Frohn). Five nested brightness levels, decimated.
Usage: build_milkyway.py <mw.json> <out.js>"""
import json, sys, math

src, out = sys.argv[1], sys.argv[2]
mw = json.load(open(src, encoding="utf-8"))
levels = []
for f in mw["features"]:                         # ol1 (faintest, widest) .. ol5 (brightest core)
    polys = []
    for poly in f["geometry"]["coordinates"]:
        for ring in poly:
            pts, last = [], None
            for ra, dec in ring:
                ra %= 360
                # keep a point once it's ~0.8° from the last one kept
                if last and math.hypot((ra - last[0]) * math.cos(math.radians(dec)), dec - last[1]) < 0.8:
                    continue
                pts += [round(ra, 2), round(dec, 2)]
                last = (ra, dec)
            if len(pts) >= 6:
                polys.append(pts)
    levels.append(polys)
with open(out, "w", encoding="utf-8") as o:
    o.write(".pragma library\n\n")
    o.write("// Generated by tools/build_milkyway.py from d3-celestial v0.7.32 mw.json\n")
    o.write("// (BSD-3-Clause, Copyright (c) 2015 Olaf Frohn). J2000 RA/Dec in degrees.\n")
    o.write("// LEVELS[0] is the faint outer glow, LEVELS[4] the brightest star clouds.\n")
    o.write("var LEVELS = " + json.dumps(levels, separators=(",", ":")) + "\n")
print([sum(len(p) // 2 for p in l) for l in levels], "points per level")
